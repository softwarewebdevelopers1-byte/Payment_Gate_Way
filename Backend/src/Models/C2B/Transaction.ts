import mongoose, { Schema, Document } from "mongoose";

export interface ITransaction extends Document {
  internalTxId: string; // Unique UUID generated by your gateway
  serviceName: string; // Originating app (e.g., "lernesis", "hostelix")
  phoneNumber: string; // Customer's phone number (e.g., 2547XXXXXXXX)
  amount: number; // Transaction amount
  accountReference: string; // Reference tag (e.g., "Room10_Rent")
  checkoutRequestID?: string; // Safaricom's STK Checkout ID
  merchantRequestID?: string; // Safaricom's Merchant ID
  mpesaReceiptNumber?: string; // Final M-Pesa receipt when successful collection occurs
  status: "PENDING" | "COMPLETED" | "FAILED" | "CANCELLED";
  resultCode?: number | string; // Daraja ResultCode
  resultDesc?: string; // Description from Safaricom callback/query
  clientCallbackUrl: string; // Where your gateway will notify the calling service back

  //  New Fields for Dynamic B2C Payout Routing
  recipientDetails?: {
    type: "phone" | "till" | "paybill";
    destination: string; // Recipient's phone number or till/paybill number
    name?: string; // Optional name of the recipient (e.g. Landlord name)
  };
  disbursementStatus?: "PENDING" | "PROCESSING" | "DISBURSED" | "FAILED";
  recipientReceiptNumber?: string; // M-Pesa receipt for the outgoing B2C payout

  createdAt: Date;
  updatedAt: Date;
}

const TransactionSchema: Schema = new Schema(
  {
    internalTxId: { type: String, required: true, unique: true, index: true },
    serviceName: { type: String, required: true, index: true },
    phoneNumber: { type: String, required: true },
    amount: { type: Number, required: true },
    accountReference: { type: String, required: true },
    checkoutRequestID: { type: String, index: true, sparse: true },
    merchantRequestID: { type: String },
    mpesaReceiptNumber: { type: String, index: true, sparse: true },
    status: {
      type: String,
      enum: ["PENDING", "COMPLETED", "FAILED", "CANCELLED"],
      default: "PENDING",
      index: true,
    },
    resultCode: { type: Schema.Types.Mixed },
    resultDesc: { type: String },
    clientCallbackUrl: { type: String, required: true },

    //New Schema Sub-document & Fields for B2C Payouts
    recipientDetails: {
      type: {
        type: String,
        enum: ["phone", "till", "paybill"],
      },
      destination: { type: String },
      name: { type: String },
    },
    disbursementStatus: {
      type: String,
      enum: ["PENDING", "PROCESSING", "DISBURSED", "FAILED"],
      default: "PENDING",
      index: true,
    },
    recipientReceiptNumber: { type: String, index: true, sparse: true },
  },
  {
    timestamps: true, // Automatically adds createdAt and updatedAt fields
  },
);

export default mongoose.model<ITransaction>("Transaction", TransactionSchema);
